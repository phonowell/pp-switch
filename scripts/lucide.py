"""Generate native FLTK vector paths from the pinned Lucide SVGs.

Development only: fonttools==4.60.1. The app ships no SVG parser or icon runtime.
"""
import argparse
from pathlib import Path
import shutil
import subprocess
import tempfile
import xml.etree.ElementTree as ET
from fontTools.svgLib.path import parse_path
from fontTools.pens.recordingPen import RecordingPen

ROOT = Path(__file__).resolve().parents[1]
ICONS = {"Settings": "settings", "Edit": "pencil", "Switch": "arrow-right-left",
         "Back": "arrow-left", "Add": "plus", "Circle": "circle",
         "Selected": "circle-dot", "Down": "chevron-down"}


def point(p):
    return f"({p[0]:.9f}, {p[1]:.9f})"


def generate():
    lines = ["// Generated by scripts/lucide.py; edit assets/lucide SVG sources instead.",
             "// Lucide 70562c1ee1c4fdcf736fe97bc893fb8511927934; ISC/MIT.",
             "use fltk::draw;", "#[derive(Clone, Copy)]", "pub enum Icon {",
             ",".join(ICONS), "}",
             "pub fn draw(icon: Icon, x: i32, y: i32, size: i32) {",
             "draw::push_matrix();", "draw::translate(x as f64, y as f64);",
             "draw::scale_xy(size as f64 / 24., size as f64 / 24.);",
             "draw::set_line_style(draw::LineStyle::Solid | draw::LineStyle::CapRound | draw::LineStyle::JoinRound, 2);",
             "match icon {"]
    for variant, filename in ICONS.items():
        lines.append(f"Icon::{variant} => {{")
        root = ET.parse(ROOT / "assets/lucide" / f"{filename}.svg").getroot()
        for element in root:
            tag = element.tag.split("}")[-1]
            if tag == "circle":
                lines += ["draw::begin_line();",
                          f"draw::draw_circle({float(element.attrib['cx'])}, {float(element.attrib['cy'])}, {float(element.attrib['r'])});",
                          "draw::end_line();"]
                continue
            if tag != "path":
                raise ValueError(f"Unsupported SVG element: {filename}/{tag}")
            pen = RecordingPen()
            parse_path(element.attrib["d"], pen)
            first = current = None
            for command, points in pen.value:
                if command == "moveTo":
                    first = current = points[0]
                    lines += ["draw::begin_line();", f"draw::vertex{point(current)};"]
                elif command == "lineTo":
                    current = points[0]
                    lines.append(f"draw::vertex{point(current)};")
                elif command == "curveTo":
                    lines.append("draw::draw_curve(" + ",".join("draw::Coord"+point(p) for p in (current, *points)) + ");")
                    current = points[-1]
                elif command in ("closePath", "endPath"):
                    if command == "closePath":
                        lines.append(f"draw::vertex{point(first)};")
                    lines.append("draw::end_line();")
                else:
                    raise ValueError(f"Unsupported path command: {command}")
        lines.append("}")
    lines += ["}", "draw::pop_matrix();",
              "draw::set_line_style(draw::LineStyle::Solid, 0);", "}"]
    with tempfile.TemporaryDirectory() as temp:
        path = Path(temp) / "lucide.rs"
        path.write_text("\n".join(lines) + "\n")
        rustfmt = shutil.which("rustfmt") or str(Path.home() / ".cargo/bin/rustfmt")
        subprocess.run([rustfmt, "--edition", "2024", str(path)], check=True)
        return path.read_text()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    destination = ROOT / "src/ui/lucide.rs"
    text = generate()
    if args.check:
        if destination.read_text() != text:
            raise SystemExit("Generated Lucide paths differ from SVG sources")
    else:
        destination.write_text(text)
    print("Lucide SVG/native path parity passed")
