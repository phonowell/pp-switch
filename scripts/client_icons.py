"""Compile pinned client brand SVG shapes; development-only fonttools dependency."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import tempfile
import xml.etree.ElementTree as ET
from fontTools.svgLib.path import parse_path
from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.boundsPen import BoundsPen

ROOT = Path(__file__).resolve().parents[1]
ICONS = {"Claude": "claude", "Codex": "openai", "Gemini": "gemini", "Grok": "grok", "Dsh": "deepseek"}


def point(p):
    return f"({p[0]:.9f}, {p[1]:.9f})"


def generate():
    manifest = json.loads((ROOT / "assets/clients/sources.json").read_text())
    for filename in ICONS.values():
        data = (ROOT / "assets/clients" / f"{filename}.svg").read_bytes()
        if hashlib.sha256(data).hexdigest() != manifest["sha256"][filename]:
            raise ValueError(f"Pinned client SVG hash mismatch: {filename}")
    lines = ["// Generated by scripts/client_icons.py from pinned Lobe Icons SVGs; MIT.",
             "use crate::provider::Client;", "use fltk::draw;",
             "// SVG coordinates can coincide with mathematical constants.",
             "#[allow(clippy::approx_constant)]",
             "pub fn draw(client: Client, x: i32, y: i32, size: i32) {",
             "draw::push_matrix();", "draw::translate(x as f64, y as f64);",
             "draw::scale_xy(size as f64 / 24., size as f64 / 24.);", "match client {"]
    for variant, filename in ICONS.items():
        lines.append(f"Client::{variant} => {{")
        root = ET.parse(ROOT / "assets/clients" / f"{filename}.svg").getroot()
        paths = root.findall("{http://www.w3.org/2000/svg}path")
        # Equal visual extents and padding, not just equal SVG viewBoxes.
        bounds = BoundsPen(None)
        for element in paths:
            parse_path(element.attrib["d"], bounds)
        x0, y0, x1, y1 = bounds.bounds
        scale = 20 / max(x1 - x0, y1 - y0)
        tx, ty = 12 - (x0 + x1) * scale / 2, 12 - (y0 + y1) * scale / 2
        lines += ["draw::push_matrix();", f"draw::translate({tx:.9f}, {ty:.9f});",
                  f"draw::scale_xy({scale:.9f}, {scale:.9f});"]
        seen = set()
        for element in paths:
            path = element.attrib["d"]
            if path in seen:
                continue
            seen.add(path)
            pen = RecordingPen()
            parse_path(path, pen)
            lines.append("draw::begin_complex_polygon();")
            first = current = None
            for command, points in pen.value:
                if command == "moveTo":
                    first = current = points[0]
                    lines.append(f"draw::vertex{point(current)};")
                elif command == "lineTo":
                    current = points[0]
                    lines.append(f"draw::vertex{point(current)};")
                elif command == "curveTo":
                    lines.append("draw::draw_curve(" + ",".join("draw::Coord" + point(p) for p in (current, *points)) + ");")
                    current = points[-1]
                elif command in ("closePath", "endPath"):
                    if command == "closePath":
                        lines.append(f"draw::vertex{point(first)};")
                    lines.append("draw::gap();")
                else:
                    raise ValueError(f"Unsupported command: {command}")
            lines.append("draw::end_complex_polygon();")
        lines += ["draw::pop_matrix();", "}"]
    lines += ["}", "draw::pop_matrix();", "}"]
    with tempfile.TemporaryDirectory() as temp:
        path = Path(temp) / "client_icons.rs"
        path.write_text("\n".join(lines) + "\n")
        rustfmt = shutil.which("rustfmt") or str(Path.home() / ".cargo/bin/rustfmt")
        subprocess.run([rustfmt, "--edition", "2024", str(path)], check=True)
        return path.read_text()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generate()
    destination = ROOT / "src/ui/client_icons.rs"
    if args.check:
        if destination.read_text() != text:
            raise SystemExit("Client icon paths differ from pinned SVGs")
    else:
        destination.write_text(text)
    print("Client SVG/native path parity passed")
